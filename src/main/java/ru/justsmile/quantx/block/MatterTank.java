package ru.justsmile.quantx.block;

/**
 * Блок, содержащий материю: к нему можно доливать и из него можно забирать.
 * Реализуют материализатор и хранилища. Квантовые волокна и хабы
 * перекачивают материю между соседними MatterTank.
 */
public interface MatterTank {

    /** Текущее количество материи в микро-единицах. */
    long getMatterMicro();

    /** Максимальная ёмкость в микро-единицах. */
    long getCapacityMicro();

    /**
     * Долить материю. Возвращает сколько реально принято (может быть 0 —
     * бак полон).
     */
    long addMatter(long micro);

    /**
     * Забрать материю. Возвращает сколько реально отдано (может быть 0 —
     * бак пуст).
     */
    long takeMatter(long micro);

    /**
     * Максимальная скорость обмена с сетью, мк/тик.
     * По умолчанию — эталонная скорость сегмента волокна (100 ед/с).
     * Старшие тиры переопределяют больше.
     */
    default long getTransferRateMicro() {
        return QuantumFiberBlockEntity.RATE_MICRO;
    }
}
