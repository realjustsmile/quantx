package ru.justsmile.quantx.block;

/**
 * Блок-хранилище материи. Сам материю НЕ хранит — только расширяет
 * счётную ёмкость материализатора, если соединён с ним напрямую
 * или через сеть квантовых волокон/хабов ({@link MatterConduit}).
 * Одно хранилище, достижимое несколькими материализаторами, делит
 * свою добавку поровну между ними.
 */
public interface MatterStorageProvider {

    /** Дополнительная ёмкость в микро-единицах материи. */
    long getMatterCapacityBonusMicro();
}
